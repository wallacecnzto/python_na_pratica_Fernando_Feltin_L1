# 16 - Escreva um programa que pede que o usuário dê entrada em dois valores, em seguida, exiba em tela o resultado da
# soma, subtração, multiplicação e divisão desses números:

primeiro_valor = int(input("Digite o primeiro valor: "))
segundo_valor = int(input("Digite o segundo valor: "))

print(f"A soma de {primeiro_valor} com {segundo_valor} é: {primeiro_valor + segundo_valor}")
print(f"A subtração de {primeiro_valor} com {segundo_valor} é: {primeiro_valor - segundo_valor}")
print(f"A multiplicação de {primeiro_valor} com {segundo_valor} é: {primeiro_valor * segundo_valor}")
print(f"A divisão de {primeiro_valor} com {segundo_valor} é: {primeiro_valor / segundo_valor}")


